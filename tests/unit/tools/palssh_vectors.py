#!/usr/bin/env python3
"""Test vectors for sdk/palssh, computed independently of the C code (hashlib and hmac only).

Run:  python3 tests/unit/tools/palssh_vectors.py
It prints the C constants used by tests/unit/test_palssh.c. The values are fixed inputs from RFC 4253 section 8
(exchange hash), section 7.2 (key derivation), the SSH fingerprint format (ssh-keygen -l -E sha256) and the
known_hosts hashed entry format (sshd(8)). Nothing here depends on the C library."""
import base64
import hashlib
import hmac
import struct


def ssh_string(b: bytes) -> bytes:
    return struct.pack(">I", len(b)) + b


def ssh_mpint(b: bytes) -> bytes:
    b = b.lstrip(b"\0")
    if not b:
        return struct.pack(">I", 0)
    if b[0] & 0x80:
        b = b"\0" + b
    return ssh_string(b)


def b64(b: bytes) -> str:
    return base64.b64encode(b).decode()


def hexc(b: bytes) -> str:
    return ", ".join("0x%02x" % x for x in b)


pk = bytes(range(1, 33))
host_blob = ssh_string(b"ssh-ed25519") + ssh_string(pk)
fingerprint = "SHA256:" + b64(hashlib.sha256(host_blob).digest()).rstrip("=")

V_C = b"SSH-2.0-PalanuOS_1.0"
V_S = b"SSH-2.0-OpenSSH_9.6"
I_C = bytes([20]) + bytes(range(16)) + b"client-kexinit-tail-bytes-0123456789"
I_S = bytes([20]) + bytes(range(100, 116)) + b"server-kexinit-tail-bytes-abcdefghijklm"
Q_C = bytes(range(32, 64))
Q_S = bytes(range(64, 96))
K = bytes(range(200, 232))  # top bit set: the mpint gets a 0x00 prefix

H = hashlib.sha256(
    ssh_string(V_C) + ssh_string(V_S) + ssh_string(I_C) + ssh_string(I_S) + ssh_string(host_blob)
    + ssh_string(Q_C) + ssh_string(Q_S) + ssh_mpint(K)
).digest()
sid = H


def derive(letter: bytes, n: int) -> bytes:
    k = ssh_mpint(K) + H
    out = hashlib.sha256(k + letter + sid).digest()
    while len(out) < n:
        out += hashlib.sha256(k + out).digest()
    return out[:n]


# known_hosts: hashed entries and the port form
salt = bytes(range(10, 30))
hashed_plain = "|1|%s|%s" % (b64(salt), b64(hmac.new(salt, b"example.test", hashlib.sha1).digest()))
hashed_port = "|1|%s|%s" % (b64(salt), b64(hmac.new(salt, b"[example.test]:2222", hashlib.sha1).digest()))

if __name__ == "__main__":
    print("/* generated by tests/unit/tools/palssh_vectors.py */")
    print('#define VEC_FINGERPRINT "%s"' % fingerprint)
    print('#define VEC_HOST_BLOB_B64 "%s"' % b64(host_blob))
    print("static const uint8_t vec_pk[32] = {%s};" % hexc(pk))
    print("static const uint8_t vec_H[32] = {%s};" % hexc(H))
    print("static const uint8_t vec_K[32] = {%s};" % hexc(K))
    print("static const uint8_t vec_Q_C[32] = {%s};" % hexc(Q_C))
    print("static const uint8_t vec_Q_S[32] = {%s};" % hexc(Q_S))
    print("static const uint8_t vec_I_C[%d] = {%s};" % (len(I_C), hexc(I_C)))
    print("static const uint8_t vec_I_S[%d] = {%s};" % (len(I_S), hexc(I_S)))
    print("static const uint8_t vec_chacha_C[64] = {%s};" % hexc(derive(b"C", 64)))
    print("static const uint8_t vec_chacha_D[64] = {%s};" % hexc(derive(b"D", 64)))
    print("static const uint8_t vec_gcm128_key_C[16] = {%s};" % hexc(derive(b"C", 16)))
    print("static const uint8_t vec_gcm128_iv_A[12] = {%s};" % hexc(derive(b"A", 12)))
    print("static const uint8_t vec_gcm256_key_D[32] = {%s};" % hexc(derive(b"D", 32)))
    print("static const uint8_t vec_gcm256_iv_B[12] = {%s};" % hexc(derive(b"B", 12)))
    print('#define VEC_HASHED_PLAIN "%s"' % hashed_plain)
    print('#define VEC_HASHED_PORT "%s"' % hashed_port)
