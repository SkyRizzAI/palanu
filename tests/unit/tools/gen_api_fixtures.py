#!/usr/bin/env python3
"""Encodes the small wasm modules of tests/unit/test_api_glue.c as C arrays (tests/unit/wasm_fixtures_api.h).

Each module imports palanu functions and calls them from _start, then passes the result to palanu.exit, so the app's exit
status is the import's return value. Run from the repo root:

    python3 tests/unit/tools/gen_api_fixtures.py > tests/unit/wasm_fixtures_api.h

The encoding is plain wasm 1.0 binary: type, import, function, memory, export, code, and data sections.
"""
import sys


def uleb(n):
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def name(s):
    b = s.encode()
    return uleb(len(b)) + b


def section(sid, payload):
    return bytes([sid]) + uleb(len(payload)) + payload


I32 = 0x7F
# function types: t0 (i32,i32,i32)->i32, t1 (i32)->(), t2 ()->()
TYPES = (
    uleb(3)
    + bytes([0x60, 3, I32, I32, I32, 1, I32])
    + bytes([0x60, 1, I32, 0])
    + bytes([0x60, 0, 0])
)


def module(imports, body, data):
    """imports: list of (module, field, typeidx); body: the _start code bytes; data: bytes at address 0."""
    imp = uleb(len(imports)) + b"".join(name(m) + name(f) + bytes([0x00]) + uleb(t) for m, f, t in imports)
    func_index_start = len(imports)
    funcs = uleb(1) + uleb(2)  # one defined function, type t2
    memory = uleb(1) + bytes([0x00, 0x01])
    exports = uleb(2) + name("_start") + bytes([0x00]) + uleb(func_index_start) + name("memory") + bytes([0x02, 0x00])
    code_body = uleb(0) + body + bytes([0x0B])  # no locals, the code, end
    code = uleb(1) + uleb(len(code_body)) + code_body
    seg = uleb(0) + bytes([0x41, 0x00, 0x0B]) + uleb(len(data)) + data
    data_sec = uleb(1) + seg
    return (
        b"\x00asm\x01\x00\x00\x00"
        + section(1, TYPES)
        + section(2, imp)
        + section(3, funcs)
        + section(5, memory)
        + section(7, exports)
        + section(10, code)
        + section(11, data_sec)
    )


def i32c(v):
    return bytes([0x41]) + sleb(v)  # i32.const takes a signed LEB128 immediate


def sleb(v):
    out = bytearray()
    while True:
        b = v & 0x7F
        v >>= 7
        if (v == 0 and not b & 0x40) or (v == -1 and b & 0x40):
            out.append(b)
            return bytes(out)
        out.append(b | 0x80)


CALL = lambda idx: bytes([0x10]) + uleb(idx)

# palanu.open(path, len, flags) then exit(result): the path is "/home/x" at address 0
OPEN_PATH = b"/home/x"
MOD_OPEN = module(
    [("palanu", "open", 0), ("palanu", "exit", 1)],
    i32c(0) + i32c(len(OPEN_PATH)) + i32c(1) + CALL(0) + CALL(1),
    OPEN_PATH,
)

# palanu.tcp_connect("127.0.0.1", 1, 100) then exit(result)
CONNECT_HOST = b"127.0.0.1\x00"
MOD_CONNECT = module(
    [("palanu", "tcp_connect", 0), ("palanu", "exit", 1)],
    i32c(0) + i32c(1) + i32c(100) + CALL(0) + CALL(1),
    CONNECT_HOST,
)


def c_array(name_, data):
    lines = [f"static const uint8_t {name_}[{len(data)}] = {{"]
    for i in range(0, len(data), 12):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 12]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    out = [
        "/* Hand-encoded wasm modules for tests/unit/test_api_glue.c, GENERATED by tests/unit/tools/gen_api_fixtures.py.",
        " * Do not edit: change the generator and run it again. */",
        "#ifndef WASM_FIXTURES_API_H",
        "#define WASM_FIXTURES_API_H",
        "",
        "#include <stdint.h>",
        "",
        c_array("WASM_OPEN_HOME", MOD_OPEN),
        "",
        c_array("WASM_CONNECT", MOD_CONNECT),
        "",
        "#endif",
        "",
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
