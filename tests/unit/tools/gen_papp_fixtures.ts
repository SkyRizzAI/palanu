#!/usr/bin/env bun
// Writes tests/unit/papp_fixtures.h: one raw DEFLATE stream (zlib, level 9) of the test module used by test_papp.c.
//   bun tests/unit/tools/gen_papp_fixtures.ts
// The module is a WebAssembly header followed by PAYLOAD_LEN - 8 bytes where byte i is (i - 8) % 37, the same rule as
// payload_fill() in test_papp.c. Signatures are not stored here: test_papp.c signs with fixed seeds at run time.
import { deflateRawSync } from "node:zlib";
import { writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { packPapp } from "../../../forge/packages/papp/src/index.ts";

const PAYLOAD_LEN = 4104;
const payload = new Uint8Array(PAYLOAD_LEN);
payload.set([0, 0x61, 0x73, 0x6d, 1, 0, 0, 0]);
for (let i = 8; i < PAYLOAD_LEN; i++) payload[i] = (i - 8) % 37;
const comp = deflateRawSync(payload, { level: 9 });

// A package made by the Forge packer (format 2, signed with the seed test_papp.c calls SEED_OK), so the device parser is
// checked against the real writer, not only against the test's own builder.
const SEED_OK = Uint8Array.from({ length: 32 }, (_, i) => i + 1);
const ts = packPapp(payload.subarray(0, 8 + 37), { id: "tsdemo", kind: "gui", perm: ["net"], hidden: true, icon: "tsicon" }, { sign: SEED_OK });
const tsRows: string[] = [];
for (let i = 0; i < ts.length; i += 16) tsRows.push("    " + [...ts.subarray(i, i + 16)].map((b) => "0x" + b.toString(16).padStart(2, "0")).join(", ") + ",");

const rows: string[] = [];
for (let i = 0; i < comp.length; i += 16) rows.push("    " + [...comp.subarray(i, i + 16)].map((b) => "0x" + b.toString(16).padStart(2, "0")).join(", ") + ",");
const out = `/* GENERATED by tests/unit/tools/gen_papp_fixtures.ts. Do not edit by hand. */
#ifndef PAPP_FIXTURES_H
#define PAPP_FIXTURES_H

#define FX_PAYLOAD_LEN ${PAYLOAD_LEN}u
#define FX_DEFLATE_LEN ${comp.length}u
static const unsigned char FX_DEFLATE[FX_DEFLATE_LEN] = {
${rows.join("\n")}
};
#define FX_TS_LEN ${ts.length}u
static const unsigned char FX_TS_SIGNED[FX_TS_LEN] = {
${tsRows.join("\n")}
};

#endif
`;
const dest = join(resolve(import.meta.dir, ".."), "papp_fixtures.h");
writeFileSync(dest, out);
console.log(`wrote ${dest}: ${comp.length} bytes deflated from ${PAYLOAD_LEN}`);
