#!/usr/bin/env bun
// PalanuOS developer tool: build, test, simulate, flash, and enforce the code rules.
//   ./pal check | test | sim | golden | build | flash | log | size | clean | hwtest
import { cpus } from "node:os";
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { apiCheckOutputs } from "../packages/apigen/src/generate.ts";
import { compareLedger } from "../packages/apigen/src/ledger.ts";
import { appgenCheck } from "../packages/appgen/src/generate.ts";

const ROOT = resolve(import.meta.dir, "../..");
const IDF_EXPORT = `${process.env.HOME}/esp/esp-idf/export.sh`;
const TARGET_DIR = join(ROOT, "targets/hhv2");
const HOST_BUILD = join(ROOT, "build/host");
const BAUD = process.env.PAL_BAUD ?? "230400";

/* Run a program with an argument vector, so arguments containing spaces survive. */
function run(argv: string[], cwd = ROOT): number {
  return Bun.spawnSync(argv, { cwd, stdout: "inherit", stderr: "inherit", stdin: "inherit" }).exitCode ?? 1;
}

function sh(cmd: string, opts: { cwd?: string; quiet?: boolean } = {}): number {
  const p = Bun.spawnSync(["bash", "-c", cmd], {
    cwd: opts.cwd ?? ROOT,
    stdout: opts.quiet ? "ignore" : "inherit",
    stderr: opts.quiet ? "ignore" : "inherit",
  });
  return p.exitCode ?? 1;
}

/* PALANU_DESKTOPS="athena" (or "classic,athena", or "" for none) picks the desktop sessions the firmware ships; unset keeps the last choice. */
function desktopsDef(): string {
  const d = process.env.PALANU_DESKTOPS;
  if (d === undefined) return "";
  if (!/^[a-z,; ]*$/.test(d)) throw new Error("PALANU_DESKTOPS: desktop ids separated by commas");
  return `-DPALANU_DESKTOPS="${d.split(/[,; ]+/).filter(Boolean).join(";")}" `;
}

function idf(cmd: string): number {
  if (!existsSync(IDF_EXPORT)) {
    console.error(`ESP-IDF not found at ${IDF_EXPORT}. See SETUP-ESP-IDF.md.`);
    return 1;
  }
  return sh(`export PATH=/opt/homebrew/bin:$PATH; . ${IDF_EXPORT} >/dev/null 2>&1; cd ${TARGET_DIR} && ${cmd}`);
}

/* The internal RAM budget of the linked firmware (forge/tools/ramcheck.ts): Wi-Fi and BLE must keep fitting together. */
function ramcheck(): number {
  return idf(`bun ${join(ROOT, "forge/tools/ramcheck.ts")}`);
}

function port(): string {
  if (process.env.PAL_PORT) return process.env.PAL_PORT;
  const found = readdirSync("/dev").filter((f) => f.startsWith("cu.usbserial"));
  if (found.length === 0) throw new Error("no /dev/cu.usbserial-* device; set PAL_PORT");
  return `/dev/${found[0]}`;
}

// ---------------------------------------------------------------- check (code rules)
function* walk(dir: string): Generator<string> {
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (["build", "managed_components", "node_modules"].includes(name)) continue;
    const st = statSync(p);
    if (st.isDirectory()) yield* walk(p);
    else if (/\.(c|h)$/.test(name)) yield p;
  }
}

/* Layers, bottom to top: apps -> system (pal/ API) -> nema -> port. A file may include headers from its own
 * layer or below. LAYER_ABOVE lists, per layer, the top-level directories it must never include from. */
const LAYER_ABOVE: Record<string, string[]> = {
  nema: ["system", "apps", "platform", "boards", "targets"],
  system: ["apps", "platform", "boards", "targets"],
  apps: ["platform", "boards", "targets"],
};

/* The only libc headers portable code may include. Any other <...> header is an OS or platform header. */
const LIBC_OK = new Set([
  "stdint.h", "stdbool.h", "stddef.h", "stdarg.h", "string.h", "stdio.h", "stdlib.h",
  "ctype.h", "limits.h", "assert.h", "inttypes.h", "math.h", "setjmp.h",
]);

/* Documented exceptions. An entry exempts one file from the listed rules, and its reason says why. An entry that
 * matches no violation is an error, so the table cannot outlive the code it excuses. */
const ALLOW: { file: string; rules: string[]; reason: string; used?: boolean }[] = [
  {
    file: "system/src/font_fallback_data.c",
    rules: ["file length"],
    reason: "generated by forge/tools/fontpack.ts: one table of glyph bytes, nothing to read or split",
  },
  {
    file: "apps/cmd_ssh.c", /* removed in F4 */
    rules: ["non-portable header", "object reach-in"],
    reason: "libssh client and ops->ioctl(NEMA_NETIOC_GETFD) for the socket fd, until the F4 socket API (removed in F4)",
  },
  {
    file: "system/src/wasm_rt.c",
    rules: ["unresolved header"],
    reason: "WAMR runtime header from third_party/wamr (ADR-0003)",
  },
  {
    file: "system/src/api_wasm.h",
    rules: ["unresolved header"],
    reason: "WAMR runtime header: the hooks the generated palanu import table calls (T2.1)",
  },
  {
    file: "system/src/athena/athena_int.h",
    rules: ["unresolved header"],
    reason: "LVGL header from third_party/lvgl: the Athena session, included by its parts through athena_int.h (ADR-0009, ADR-0010)",
  },
  {
    file: "system/src/cryptoimpl_mbedtls.c",
    rules: ["unresolved header"],
    reason: "PSA Crypto header of ESP-IDF (TF-PSA-Crypto), present only in the ESP build (T2.6)",
  },
];

/* Board names stay out of system/ and apps/: they ask for capabilities (pal_has), never for a board. Only string
 * literals and identifiers are checked; prose in comments may name a board. Exceptions go in ALLOW with rule
 * "board name". */
const BOARD_NAME = /\bHHV2_|\bhhv2_|\bhhv2\b/;

/* Where an #include lands in the tree, or null. Quoted names are tried beside the including file first, then the
 * public include roots: nema/include for nema/..., system/include for pal/... . */
function resolveInclude(from: string, quoted: boolean, name: string): string | null {
  const cands: string[] = [];
  if (quoted) cands.push(join(dirname(from), name));
  if (name.startsWith("nema/")) cands.push(join(ROOT, "nema/include", name));
  if (name.startsWith("pal/")) cands.push(join(ROOT, "system/include", name));
  if (name.includes("/")) cands.push(join(ROOT, name));
  return cands.find((p) => existsSync(p)) ?? null;
}

function check(): number {
  const portable = ["nema", "system", "apps"].map((d) => join(ROOT, d));
  const rules: { name: string; re: RegExp; scope: "portable" | "all-but-platform"; hint: string }[] = [
    {
      name: "platform include in portable code",
      re: /#\s*include\s*[<"](freertos\/|esp_|driver\/|soc\/|hal\/|nvs|lwip\/|sdkconfig|SDL)/,
      scope: "portable",
      hint: "portable code may only include nema/ and pal/ headers; use nema_port.h",
    },
    {
      name: "raw allocation",
      re: /(?<![A-Za-z0-9_])(malloc|calloc|realloc|free|heap_caps_\w+)\s*\(/,
      scope: "all-but-platform",
      hint: "use nema_alloc()/nema_free() with a class and an owner",
    },
  ];
  let errors = 0;
  let warns = 0;
  const fail = (where: string, rule: string, hint: string) => {
    console.error(`${where}: ${rule}: ${hint}`);
    errors++;
  };
  /* True when the table excuses this file from the rule; marks the entry as used. */
  const exempt = (rel: string, rule: string): boolean => {
    const e = ALLOW.find((a) => a.file === rel && a.rules.includes(rule));
    if (e) e.used = true;
    return e !== undefined;
  };

  for (const top of ["nema", "system", "apps", "platform", "boards", "targets"]) {
    for (const file of walk(join(ROOT, top))) {
      const rel = relative(ROOT, file);
      const layer = rel.split("/")[0];
      const isPortable = portable.some((d) => file.startsWith(d + "/"));
      const isPlatform = rel.startsWith("platform/") || rel.startsWith("boards/") || rel.startsWith("targets/");
      const text = readFileSync(file, "utf8");
      const lines = text.split("\n");
      // block comments are blanked (keeping line numbers) so prose cannot trip the rules
      const stripped = text.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " ")).split("\n");
      if (lines.length > 1000 && exempt(rel, "file length")) { /* generated data, see ALLOW */ }
      else if (lines.length > 1000) { console.error(`${rel}: ${lines.length} lines (limit 1000)`); errors++; }
      else if (lines.length > 800) { console.warn(`${rel}: ${lines.length} lines (soft limit 800)`); warns++; }

      const checkInclude = (where: string, quoted: boolean, name: string) => {
        const flag = (rule: string, hint: string) => {
          if (!exempt(rel, rule)) fail(where, rule, hint);
        };
        if (LIBC_OK.has(name)) return;
        const target = resolveInclude(file, quoted, name);
        if (!target) {
          const up = LAYER_ABOVE[layer].find((d) => existsSync(join(ROOT, d, name)));
          if (up) return flag("layer include", `${layer}/ must not include ${up}/ headers (${name})`);
          if (!quoted && !name.startsWith("nema/") && !name.startsWith("pal/"))
            return flag("non-portable header", `<${name}> is not a portable libc header; use nema/port.h or a pal/ API`);
          return flag("unresolved header", `"${name}" cannot be resolved; a third-party header needs an ALLOW entry`);
        }
        const tgt = relative(ROOT, target);
        const tl = tgt.split("/")[0];
        if (LAYER_ABOVE[layer].includes(tl))
          return flag("layer include", `${layer}/ must not include ${tl}/ headers (${tgt}); lower layers never include higher ones`);
        if (layer === "apps" && tgt.startsWith("nema/src/"))
          return flag("private header", `apps/ may not include the nema private header ${tgt}`);
        if (layer === "apps" && tgt === "nema/include/nema/port.h")
          return flag("layer include", "apps/ may not include nema/port.h; use a pal/ API");
      };

      stripped.forEach((line, i) => {
        const where = `${rel}:${i + 1}`;
        const code = line.replace(/\/\/.*$/, "").replace(/"(\\.|[^"\\])*"/g, '""');
        for (const r of rules) {
          if (r.scope === "portable" && !isPortable) continue;
          if (r.scope === "all-but-platform" && isPlatform) continue;
          if (r.name === "platform include in portable code" ? r.re.test(line) : r.re.test(code)) fail(where, r.name, r.hint);
        }
        const inc = /^\s*#\s*include\s*([<"])([^>"]+)[>"]/.exec(line);
        if (inc && (layer === "nema" || layer === "system" || layer === "apps")) checkInclude(where, inc[1] === '"', inc[2]);
        if ((layer === "system" || layer === "apps") && BOARD_NAME.test(line.replace(/\/\/.*$/, "")) && !exempt(rel, "board name"))
          fail(where, "board name", "system/ and apps/ ask for capabilities with pal_has(), not a board name");
        if (layer === "apps" && /\bnema_port_\w+\s*\(/.test(code) && !exempt(rel, "nema_port call"))
          fail(where, "nema_port call", "apps/ use the pal_sys_* API (pal/sysinfo.h), not nema_port_* directly");
        if ((layer === "apps" || layer === "system") && /->\s*ops\s*->/.test(code) && !exempt(rel, "object reach-in"))
          fail(where, "object reach-in", "apps/ and system/ use the nema_obj_* API, not ->ops->");
      });
    }
  }

  // ADR numbers are the cross-reference key, so no two records may share one.
  const adrDir = join(ROOT, "docs/adr");
  const adrNum = new Map<string, string>();
  for (const f of existsSync(adrDir) ? readdirSync(adrDir).sort() : []) {
    const m = /^(\d{4})-.*\.md$/.exec(f);
    if (!m) continue;
    const prev = adrNum.get(m[1]);
    if (prev) fail(`docs/adr/${f}`, "duplicate ADR number", `ADR ${m[1]} is already used by ${prev}`);
    else adrNum.set(m[1], f);
  }

  // API (T2.1): the generated outputs match their definitions, and no released name changed since HEAD (the ledger).
  const api = apiCheckOutputs(ROOT);
  for (const msg of api.warnings) {
    console.warn(`warning: ${msg}`);
    warns++;
  }
  for (const msg of api.errors) {
    console.error(msg);
    errors++;
  }
  const headLedger = Bun.spawnSync(["git", "show", "HEAD:api/symbols.csv"], { cwd: ROOT, stdout: "pipe", stderr: "ignore" });
  if (headLedger.exitCode === 0) {
    const ledgerPath = join(ROOT, "api/symbols.csv");
    const work = existsSync(ledgerPath) ? readFileSync(ledgerPath, "utf8") : "";
    for (const msg of compareLedger(new TextDecoder().decode(headLedger.stdout), work)) {
      console.error(msg);
      errors++;
    }
  }

  // Chip ROM symbols (found on the board, T2.10): the ESP32-S31 ROM linker scripts define names such as tinfl_decompress
  // and memcpy at fixed addresses, and a script assignment beats a function of the same name in our objects, so the
  // firmware silently calls the ROM version. A non-static function of ours with a ROM name must be renamed.
  const romDir = `${process.env.HOME}/esp/esp-idf/components/esp_rom/esp32s31/ld`;
  if (existsSync(romDir)) {
    const rom = new Set<string>();
    for (const f of readdirSync(romDir).filter((n) => n.endsWith(".ld"))) {
      for (const l of readFileSync(join(romDir, f), "utf8").split("\n")) {
        const m = /^\s*(?:PROVIDE\()?\s*([A-Za-z_]\w*)\s*=\s*0x[0-9a-fA-F]+/.exec(l);
        if (m) rom.add(m[1]);
      }
    }
    const roots = ["nema", "system", "apps", "platform/net_bsd", "platform/posix_fs", "third_party/miniz", "third_party/monocypher", "boards"];
    const defRe = /^[A-Za-z_][\w\s\*]*?[\s\*]([A-Za-z_]\w*)\s*\([^;{}]*\)\s*\{?\s*$/;
    const walk = (dir: string, out: string[] = []): string[] => {
      for (const e of readdirSync(dir)) {
        const p = join(dir, e);
        if (statSync(p).isDirectory()) walk(p, out);
        else if (p.endsWith(".c")) out.push(p);
      }
      return out;
    };
    // Documented exceptions. tinfl_*: renamed at compile time by TINFL_RENAME in system/CMakeLists.txt and
    // platform/host/CMakeLists.txt, so the object file does not define the ROM names.
    const allowRom = new Set<string>(["tinfl_decompress", "tinfl_decompress_mem_to_heap", "tinfl_decompress_mem_to_mem", "tinfl_decompress_mem_to_callback"]);
    for (const r of roots) {
      const dir = join(ROOT, r);
      if (!existsSync(dir)) continue;
      for (const file of walk(dir)) {
        const defines = (readFileSync(file, "utf8").split("\n"));
        defines.forEach((line, i) => {
          const t = line.trim();
          if (t.startsWith("static") || t.startsWith("extern") || t.startsWith("return") || t.startsWith("#")) return;
          const m = defRe.exec(t);
          if (!m || !rom.has(m[1]) || allowRom.has(m[1])) return;
          console.error(`${relative(ROOT, file)}:${i + 1}: rom symbol: ${m[1]}() is also defined in the chip ROM; the ROM one would win at link time (rename ours)`);
          errors++;
        });
      }
    }
  }

  // Built-in apps (T2.9): apps/apps.toml is valid and apps/manifests.gen.c is up to date.
  for (const msg of appgenCheck(ROOT)) {
    console.error(`appgen: ${msg}`);
    errors++;
  }
  // Icons (T5.14): the generated icon tables (system/src/icons_data.c) are what assets/icons/ produces.
  if (run([process.execPath, join(ROOT, "forge/tools/icons.ts"), "--check"]) !== 0) errors++;
  // Animations (docs/ANIM.md): the .panim files and the generated tables (system/src/anims_data.c, system/src/anims/*.inc) are
  // what assets/anims/ produces.
  if (run([process.execPath, join(ROOT, "forge/tools/panim.ts"), "--check"]) !== 0) errors++;
  for (const e of ALLOW) if (!e.used) fail(e.file, "stale allowlist entry", `no matching violation; remove it (${e.reason})`);

  { /* the version lives in three places that `./pal release` writes together */
    const ver = readFileSync(join(ROOT, "VERSION"), "utf8").trim();
    const hdr = /PAL_OS_VERSION "([^"]*)"/.exec(readFileSync(join(ROOT, "system/include/pal/version.h"), "utf8"))?.[1];
    const cl = /^## (\S+)/m.exec(existsSync(join(ROOT, "CHANGELOG.md")) ? readFileSync(join(ROOT, "CHANGELOG.md"), "utf8") : "")?.[1];
    if (hdr !== ver) fail("VERSION", "version", `VERSION is ${ver} but system/include/pal/version.h says ${hdr}`);
    if (cl !== ver) fail("CHANGELOG.md", "version", `the newest CHANGELOG.md section is ${cl ?? "missing"}, VERSION is ${ver}`);
  }
  console.log(`check: ${errors} error(s), ${warns} warning(s)`);
  return errors ? 1 : 0;
}

// ---------------------------------------------------------------- host build, test, sim
function hostBuild(target?: string): number {
  const cfg = existsSync(join(HOST_BUILD, "build.ninja")) ? 0 : sh(`cmake -S platform/host -B ${HOST_BUILD} -G Ninja -DCMAKE_BUILD_TYPE=Debug`);
  if (cfg) return cfg;
  return sh(`cmake --build ${HOST_BUILD}${target ? ` --target ${target}` : ""}`);
}

// ---------------------------------------------------------------- browser simulator
const EMSDK = join(ROOT, "refs/emsdk");
const WEB_BUILD = join(ROOT, "build/web");

/** Installs Emscripten into refs/emsdk (once; needs git and Python 3.10 or newer). */
function webSetup(): number {
  if (existsSync(join(EMSDK, "emsdk"))) { console.log(`Emscripten is already in ${EMSDK}`); return 0; }
  return sh(`mkdir -p refs && git clone --depth 1 https://github.com/emscripten-core/emsdk refs/emsdk && cd refs/emsdk && ${emPython()} ./emsdk install latest && ${emPython()} ./emsdk activate latest`);
}

/** The Python that runs Emscripten's tools: EMSDK_PYTHON, else the newest python3.x on the PATH. */
function emPython(): string {
  if (process.env.EMSDK_PYTHON) return `EMSDK_PYTHON=${process.env.EMSDK_PYTHON} ${process.env.EMSDK_PYTHON}`;
  for (const v of ["3.15", "3.14", "3.13", "3.12", "3.11", "3.10"]) {
    const p = Bun.spawnSync(["bash", "-c", `command -v python${v}`]);
    if (p.exitCode === 0) { const path = p.stdout.toString().trim(); return `EMSDK_PYTHON=${path} ${path}`; }
  }
  return "python3";
}

/** Builds the system for the browser (platform/web, Emscripten). Returns 0 and skips with a note when Emscripten is absent. */
function webSystem(): number {
  if (!existsSync(join(EMSDK, "emsdk_env.sh"))) {
    console.warn("web: Emscripten not found in refs/emsdk, so the simulator will not run. Install it with: ./pal web setup");
    return 0;
  }
  const py = process.env.EMSDK_PYTHON ?? "$(command -v python3.15 || command -v python3.14 || command -v python3.13 || command -v python3.12 || command -v python3.11 || command -v python3.10 || command -v python3)";
  const env = `export EMSDK_PYTHON=${py}; source ${EMSDK}/emsdk_env.sh >/dev/null 2>&1`;
  const cfg = existsSync(join(WEB_BUILD, "build.ninja")) || existsSync(join(WEB_BUILD, "Makefile")) ? 0 : sh(`${env}; emcmake cmake -S platform/web -B ${WEB_BUILD}`);
  return cfg || sh(`${env}; cmake --build ${WEB_BUILD} -j8`);
}

function usage(): number {
  console.log(`usage: ./pal <command>
  check            enforce code rules (layers, OS headers, nema_port/ops reach-ins, ADR numbers, raw allocation, file length, API outputs and ledger)
  test             build and run the host unit tests
  sim [args]       build and run the host simulator
  golden check|update   compare the simulator screens with tests/golden/ref (update rewrites them)
  build            build the hhv2 firmware
  flash            build, flash, and reset the board (baud ${BAUD})
  log [seconds]    reset the board and print its serial output
  size             firmware size by component
  release --version X.Y.Z | --bump patch|minor|major [--board PORT] [--dry-run]   gates, changelog, dist/release/, local commit and tag
  smoke [--minutes N] [--csv F]   visit every screen on the board and watch for crashes (a soak with --minutes; 1440 is the 24 h test)
  web [--no-sim]   build the simulator system (Emscripten) and Web Forge, serve on http://localhost:5174 (simulator at /sim/)
  web setup        install Emscripten into refs/emsdk (once)
  hwtest [args]    measure a device or the simulator (default 127.0.0.1:7100), append to docs/SIZE-BUDGETS.md
  clean            remove build outputs
env: PAL_PORT, PAL_BAUD`);
  return 1;
}

const [cmd, ...rest] = process.argv.slice(2);
let code = 0;
switch (cmd) {
  case "check": code = check(); break;
  case "test": code = check() || hostBuild() || sh(`ctest --test-dir ${HOST_BUILD} --output-on-failure -j ${Math.max(2, Math.min(8, cpus().length))}`); break; // side by side: the slow ones overlap
  case "sim": code = hostBuild("palanu-sim") || run([`${HOST_BUILD}/palanu-sim`, ...rest]); break;
  case "golden": code = hostBuild("palanu-sim") || run([process.execPath, join(ROOT, "forge/tools/golden.ts"), ...rest]); break;
  case "build": code = check() || idf(`idf.py ${desktopsDef()}reconfigure build`) || ramcheck(); break;
  case "flash": code = check() || idf(`idf.py ${desktopsDef()}reconfigure build`) || ramcheck() || idf(`idf.py -p ${port()} -b ${BAUD} flash`); break;
  case "log": code = idf(`python ${ROOT}/forge/tools/serial_capture.py ${port()} ${rest[0] ?? 8}`); break;
  case "size": code = idf("idf.py size-components"); break;
  case "release": code = Bun.spawnSync([process.execPath, join(ROOT, "forge/tools/release.ts"), ...rest], { stdout: "inherit", stderr: "inherit", stdin: "inherit" }).exitCode ?? 1; break;
  case "smoke": code = idf(`python ${ROOT}/forge/tools/board_smoke.py ${port()} ${rest.join(" ")}`); break; // visits every screen on the board; --minutes N soaks
  case "web":
    if (rest[0] === "setup") { code = webSetup(); break; }
    code = (rest.includes("--no-sim") ? 0 : webSystem()) || run([process.execPath, join(ROOT, "forge/web/build.ts")]) || run([process.execPath, join(ROOT, "forge/web/serve.ts")]);
    break;
  case "hwtest": code = Bun.spawnSync([process.execPath, join(ROOT, "forge/tools/hwtest.ts"), ...rest], { stdout: "inherit", stderr: "inherit", stdin: "inherit" }).exitCode ?? 1; break;
  case "clean": code = sh(`rm -rf build targets/hhv2/build targets/hhv2/sdkconfig`); break;
  default: code = usage();
}
process.exit(code);
