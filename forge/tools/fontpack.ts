#!/usr/bin/env bun
// Pack GNU Unifont-style .hex fonts (one glyph per line, "CODEPOINT:HEXBITS", 8x16 or 16x16) into the fallback-font blob the
// terminal falls back to when the Spleen font has no glyph (system/src/font_fallback.c).
//
//   bun forge/tools/fontpack.ts embedded <out.c>  <license-file> <hex-or-hex.gz>...   the tier linked into the firmware
//   bun forge/tools/fontpack.ts file     <out.pfnt>             <hex-or-hex.gz>...   the CJK/Hangul tier, copied to /data/fonts/
//
// Blob layout (little endian, no alignment assumed by readers):
//   0   "PFN1"
//   4   u32 number of runs
//   8   u32 offset of the glyph data from the start of the blob
//   12  runs, 12 bytes each, sorted by first code point:  u32 first cp, u16 count, u8 cells (1 = 8 wide, 2 = 16 wide), u8 0,
//       u32 offset of the run's first glyph from the start of the glyph data
//   glyph data: 16 rows per glyph, `cells` bytes per row, MSB is the leftmost pixel.
// A run is a stretch of consecutive code points of the same width.
import { readFileSync, writeFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";

// Code points that live in the file tier: the ideographs and syllables that would make the firmware image too big (about 1.2 MB).
const FILE_TIER: [number, number][] = [
  [0x3400, 0x4dbf], [0x4e00, 0x9fff], [0xac00, 0xd7a3], [0xf900, 0xfaff],
];
// Never carried: the terminal draws these itself, at the exact cell size, and the Spleen font has most of the rest.
const DRAWN_BY_TERMINAL: [number, number][] = [[0x2500, 0x259f], [0x2800, 0x28ff], [0xe0a0, 0xe0bf]];
// Of the planes above the BMP only the emoji and symbol blocks (U+1F000-1FAFF) are worth the space.
const SMP_WANTED: [number, number][] = [[0x1f000, 0x1faff]];

const inRanges = (cp: number, r: [number, number][]) => r.some(([a, b]) => cp >= a && cp <= b);

type Glyph = { cp: number; cells: number; rows: Uint8Array };

function readHex(path: string): Glyph[] {
  let raw = readFileSync(path);
  if (path.endsWith(".gz")) raw = gunzipSync(raw);
  const out: Glyph[] = [];
  for (const line of raw.toString("utf8").split(/\r?\n/)) {
    const m = /^([0-9A-Fa-f]{4,6}):([0-9A-Fa-f]+)$/.exec(line.trim());
    if (!m) continue;
    const cp = parseInt(m[1], 16);
    const hex = m[2];
    if (hex.length !== 32 && hex.length !== 64) throw new Error(`${path}: U+${m[1]} has ${hex.length} hex digits (want 32 or 64)`);
    const rows = new Uint8Array(hex.length / 2);
    for (let i = 0; i < rows.length; i++) rows[i] = parseInt(hex.slice(2 * i, 2 * i + 2), 16);
    out.push({ cp, cells: hex.length / 32, rows });
  }
  return out;
}

function pack(glyphs: Glyph[]): Buffer {
  glyphs.sort((a, b) => a.cp - b.cp);
  const runs: { cp: number; count: number; cells: number; off: number }[] = [];
  let off = 0;
  for (const g of glyphs) {
    const last = runs[runs.length - 1];
    if (last && last.cells === g.cells && g.cp === last.cp + last.count && last.count < 0xffff) last.count++;
    else runs.push({ cp: g.cp, count: 1, cells: g.cells, off });
    off += g.rows.length;
  }
  const dataOff = 12 + runs.length * 12;
  const buf = Buffer.alloc(dataOff + off);
  buf.write("PFN1", 0, "ascii");
  buf.writeUInt32LE(runs.length, 4);
  buf.writeUInt32LE(dataOff, 8);
  runs.forEach((r, i) => {
    const p = 12 + i * 12;
    buf.writeUInt32LE(r.cp, p);
    buf.writeUInt16LE(r.count, p + 4);
    buf.writeUInt8(r.cells, p + 6);
    buf.writeUInt32LE(r.off, p + 8);
  });
  let p = dataOff;
  for (const g of glyphs) {
    buf.set(g.rows, p);
    p += g.rows.length;
  }
  return buf;
}

const [mode, out, ...rest] = process.argv.slice(2);
if ((mode !== "embedded" && mode !== "file") || !out || rest.length === 0) {
  console.error("usage: fontpack.ts embedded <out.c> <license-file> <hex>... | file <out.pfnt> <hex>...");
  process.exit(1);
}
const license = mode === "embedded" ? rest.shift()! : "";
const seen = new Map<number, Glyph>();
for (const f of rest) for (const g of readHex(f)) seen.set(g.cp, g); // a later file overrides an earlier one
const want = [...seen.values()].filter((g) => {
  if (inRanges(g.cp, DRAWN_BY_TERMINAL)) return false;
  if (g.cp >= 0x10000 && !inRanges(g.cp, SMP_WANTED) && !inRanges(g.cp, FILE_TIER) && g.cp < 0xf0000) return false;
  const file = inRanges(g.cp, FILE_TIER);
  return mode === "file" ? file : !file;
});
const blob = pack(want);

if (mode === "file") {
  writeFileSync(out, blob);
  console.log(`${out}: ${want.length} glyphs, ${blob.length} bytes`);
} else {
  const lic = readFileSync(license, "utf8").split(/\r?\n/).slice(0, 25).map((l) => ` * ${l}`.replace(/\*\//g, "* /")).join("\n");
  let c = `/* Generated by forge/tools/fontpack.ts from GNU Unifont 17.0.05 (and the other .hex files named in assets/fonts/unifont/README). Do not edit.\n`;
  c += ` * ${want.length} glyphs, ${blob.length} bytes of read-only data. The compiled Unifont is licensed under the SIL Open Font License 1.1\n`;
  c += ` * and the GNU GPL with the font embedding exception; the start of the notice follows, the full text is assets/fonts/unifont/LICENSE.txt.\n *\n${lic}\n */\n`;
  c += `#include <stddef.h>\n#include <stdint.h>\n\nconst uint8_t PAL_FALLBACK_BLOB[] __attribute__((aligned(4))) = {\n`;
  const lines: string[] = [];
  for (let i = 0; i < blob.length; i += 24) lines.push("    " + [...blob.subarray(i, i + 24)].map((b) => "0x" + b.toString(16).padStart(2, "0")).join(","));
  c += lines.join(",\n") + `,\n};\nconst size_t PAL_FALLBACK_BLOB_SIZE = sizeof PAL_FALLBACK_BLOB;\n`;
  writeFileSync(out, c);
  console.log(`${out}: ${want.length} glyphs, ${blob.length} bytes`);
}
