#!/usr/bin/env bun
// Font packs: converts the BMF files of a pack (assets/fonts/<Pack>/<slot>.bmf, BMF format: 12-byte header, optional
// widths and offsets, column-major glyph data) into kui_font_t tables, one C file per pack.
//   bun forge/tools/bmf2c.ts <Pack> <out.c> <symbolPrefix>
// Example: bun forge/tools/bmf2c.ts ProFont system/src/kui/font_pack_prof.c PROF
// The generated tables are FONT_PK_<prefix>_<SLOT> (SLOT = REG8, BOLD8, REG10, BOLD10, REG12, BOLD12).
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "../..");
const SLOTS = ["reg8", "bold8", "reg10", "bold10", "reg12", "bold12"];
const PER_LINE = 24;

function bytesLines(name: string, type: string, values: number[]): string {
  const rows: string[] = [];
  for (let i = 0; i < values.length; i += PER_LINE)
    rows.push("    " + values.slice(i, i + PER_LINE).map((v) => "0x" + v.toString(16).toUpperCase().padStart(2, "0")).join(", ") + ",");
  return `static const ${type} ${name}[] = {\n${rows.join("\n")}\n};\n`;
}

function convert(pack: string, slot: string, prefix: string): { code: string; ident: string } {
  const path = join(ROOT, "assets/fonts", pack, `${slot}.bmf`);
  if (!existsSync(path)) throw new Error(`missing ${path}`);
  const raw = readFileSync(path);
  if (raw[0] !== 0xbf || raw[1] !== 1) throw new Error(`${path}: not a BMF v1 file`);
  const charW = raw[2], charH = raw[3], firstChar = raw[4], numChars = raw[5], spacing = raw[6], bpc = raw[7];
  const hasW = raw[8] !== 0, hasO = raw[9] !== 0;
  const dataSize = raw[10] | (raw[11] << 8);
  let p = 12;
  const widths = hasW ? [...raw.subarray(p, p + numChars)] : null;
  p += hasW ? numChars : 0;
  const offsets: number[] = [];
  if (hasO) for (let i = 0; i < numChars; i++) offsets.push(raw[p + 2 * i] | (raw[p + 2 * i + 1] << 8));
  p += hasO ? numChars * 2 : 0;
  const data = [...raw.subarray(p, p + dataSize)];
  if (data.length !== dataSize) throw new Error(`${path}: data is short`);
  const id = `FONT_PK_${prefix}_${slot.toUpperCase()}`;
  const base = `PK_${prefix}_${slot.toUpperCase()}`;
  let code = "";
  code += bytesLines(`${base}_DATA`, "uint8_t", data);
  if (widths) code += bytesLines(`${base}_W`, "uint8_t", widths);
  if (hasO) {
    const rows: string[] = [];
    for (let i = 0; i < offsets.length; i += 12) rows.push("    " + offsets.slice(i, i + 12).join(", ") + ",");
    code += `static const uint16_t ${base}_OFF[] = {\n${rows.join("\n")}\n};\n`;
  }
  code += `const kui_font_t ${id} = {${base}_DATA, ${charW}, ${charH}, ${firstChar}, ${numChars}, ${spacing}, ${widths ? base + "_W" : "NULL"}, ${hasO ? base + "_OFF" : "NULL"}, ${bpc}};\n`;
  return { code, ident: id };
}

function main(): number {
  const [pack, out, prefix] = process.argv.slice(2);
  if (!pack || !out || !prefix) {
    console.error("usage: bun forge/tools/bmf2c.ts <Pack> <out.c> <symbolPrefix>");
    return 2;
  }
  const parts: string[] = [];
  for (const s of SLOTS) {
    const c = convert(pack, s, prefix);
    parts.push(c.code);
  }
  const head = `/* Font pack ${pack}: BMF glyph tables converted to kui fonts.\n * Generated by forge/tools/bmf2c.ts from the BMF files in assets/fonts/${pack} (one per slot). Do not edit by hand. Licence: see docs/SOURCES.md. */\n#include "pal/kui.h"\n\n`;
  writeFileSync(resolve(ROOT, out), head + parts.join("\n"));
  console.log(`wrote ${out}`);
  return 0;
}

process.exit(main());
