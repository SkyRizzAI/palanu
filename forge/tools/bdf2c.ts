#!/usr/bin/env bun
// Convert a BDF bitmap font to a C table for PalanuOS.
//   bun forge/tools/bdf2c.ts <font.bdf> <out.c> <C symbol> <font name> [license-file]
// Output is cell-based (every glyph padded to the font box), 1 bit per pixel, rows padded to whole bytes.
import { readFileSync, writeFileSync } from "node:fs";

const [bdf, out, symbol, name, licensePath] = process.argv.slice(2);
if (!bdf || !out || !symbol || !name) {
  console.error("usage: bdf2c.ts <font.bdf> <out.c> <symbol> <name> [license-file]");
  process.exit(1);
}

// Code points worth carrying: ASCII, Latin-1, general punctuation (bullets, ellipsis, dashes), arrows, technical symbols,
// box drawing and block elements, geometric shapes (the progress bars' squares), dingbats (check marks), braille (the
// spinners of modern terminal UIs) and the Powerline separators. Box drawing and blocks are also drawn by the terminal
// itself (term_draw.c) when the font has no glyph, so a small font still shows a TUI's frames.
const RANGES: [number, number][] = [
  [0x20, 0x7e], [0xa0, 0xff], [0x2010, 0x206f], [0x2190, 0x21ff], [0x2300, 0x23ff], [0x2500, 0x25ff], [0x2700, 0x27bf],
  [0x2800, 0x28ff], [0xe0a0, 0xe0d7],
];
const wanted = (cp: number) => RANGES.some(([a, b]) => cp >= a && cp <= b);

const lines = readFileSync(bdf, "utf8").split(/\r?\n/);
let fw = 0, fh = 0, fx = 0, fy = 0;
const glyphs = new Map<number, number[][]>();

for (let i = 0; i < lines.length; i++) {
  const l = lines[i];
  if (l.startsWith("FONTBOUNDINGBOX")) [fw, fh, fx, fy] = l.split(/\s+/).slice(1).map(Number);
  if (!l.startsWith("STARTCHAR")) continue;
  let enc = -1, gw = 0, gh = 0, gx = 0, gy = 0;
  const rows: string[] = [];
  for (i++; !lines[i].startsWith("ENDCHAR"); i++) {
    const m = lines[i];
    if (m.startsWith("ENCODING")) enc = Number(m.split(/\s+/)[1]);
    else if (m.startsWith("BBX")) [gw, gh, gx, gy] = m.split(/\s+/).slice(1).map(Number);
    else if (m.startsWith("BITMAP")) {
      for (i++; !lines[i].startsWith("ENDCHAR"); i++) rows.push(lines[i].trim());
      break;
    }
  }
  if (enc < 0 || !wanted(enc)) continue;
  // place the glyph into a fw x fh cell
  const cell: number[][] = Array.from({ length: fh }, () => new Array(fw).fill(0));
  const top = fh + fy - gy - gh; // cell row of the glyph's first row
  rows.forEach((hex, r) => {
    const bits = parseInt(hex.padEnd(Math.ceil(gw / 8) * 2, "0"), 16);
    const width = Math.ceil(gw / 8) * 8;
    for (let c = 0; c < gw; c++) {
      if (!((bits >> (width - 1 - c)) & 1)) continue;
      const cx = gx - fx + c, cy = top + r;
      if (cx >= 0 && cx < fw && cy >= 0 && cy < fh) cell[cy][cx] = 1;
    }
  });
  glyphs.set(enc, cell);
}

const cps = [...glyphs.keys()].sort((a, b) => a - b);
const bpr = Math.ceil(fw / 8);
const bytes: number[] = [];
for (const cp of cps) {
  for (const row of glyphs.get(cp)!) {
    for (let b = 0; b < bpr; b++) {
      let v = 0;
      for (let k = 0; k < 8; k++) v = (v << 1) | (row[b * 8 + k] ?? 0);
      bytes.push(v);
    }
  }
}

const hex = (a: number[], per: number, w: number) =>
  a.map((v, i) => (i % per === 0 ? "\n    " : " ") + "0x" + v.toString(16).padStart(w, "0") + ",").join("");
const license = licensePath ? readFileSync(licensePath, "utf8").split("\n").map((l) => " * " + l).join("\n") : "";

writeFileSync(out, `/* Generated by forge/tools/bdf2c.ts from ${bdf.split("/").pop()}. Do not edit.
 * ${name}: ${fw}x${fh} cells, ${cps.length} glyphs.
 *
${license}
 */
#include "pal/font.h"

static const uint16_t CPS[] = {${hex(cps, 12, 4)}
};

static const uint8_t BITS[] = {${hex(bytes, 16, 2)}
};

const pal_font_t ${symbol} = {"${name}", ${fw}, ${fh}, ${cps.length}, CPS, BITS};
`);
console.log(`${out}: ${fw}x${fh}, ${cps.length} glyphs, ${bytes.length} bytes`);
