#!/usr/bin/env bun
// The device's offline manual (`man`, apps/cmd_man.c): the user's docs as plain text, stored deflated in the image and inflated
// when read. Run after changing one of the docs below:   bun forge/tools/mandata.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { deflateRawSync } from "node:zlib";

const ROOT = resolve(import.meta.dir, "../..");
const TOPICS: { name: string; file: string; title: string }[] = [
  { name: "guide", file: "docs/USER-GUIDE.md", title: "Using PalanuOS" },
  { name: "keys", file: "docs/KEYMAP.md", title: "The keyboard and its layers" },
  { name: "keyboard", file: "docs/VKEYBOARD.md", title: "The on-screen keyboard and the input menu" },
  { name: "radio", file: "docs/RADIO.md", title: "Wi-Fi and Bluetooth" },
  { name: "store", file: "docs/STORE.md", title: "The app catalogue" },
  { name: "ssh", file: "docs/TESTING-SSH.md", title: "SSH from the device" },
  { name: "lua", file: "docs/LUA.md", title: "Lua on the device" },
];

/* Markdown to terminal text: headings underlined, no emphasis marks or code ticks, links as their text. */
function plain(md: string): string {
  const out: string[] = [];
  for (let line of md.split(/\r?\n/)) {
    const h = /^(#{1,3})\s+(.*)$/.exec(line);
    if (h) {
      const t = h[2].replace(/[*`]/g, "");
      out.push("", t, (h[1].length === 1 ? "=" : "-").repeat(Math.min(t.length, 60)));
      continue;
    }
    line = line.replace(/\*\*([^*]+)\*\*/g, "$1").replace(/`([^`]+)`/g, "$1").replace(/\[([^\]]+)\]\([^)]+\)/g, "$1");
    out.push(line);
  }
  return out.join("\n").replace(/\n{3,}/g, "\n\n").trim() + "\n";
}

let c = `/* Generated by forge/tools/mandata.ts from docs/ (the offline manual, apps/cmd_man.c). Do not edit. */\n#include <stddef.h>\n#include <stdint.h>\n\n`;
c += `typedef struct {\n    const char *name, *title;\n    const uint8_t *z;\n    size_t zlen, len;\n} man_topic_t;\n\n`;
const rows: string[] = [];
let raw = 0, packed = 0;
TOPICS.forEach((t, i) => {
  const text = Buffer.from(plain(readFileSync(join(ROOT, t.file), "utf8")), "utf8");
  const z = deflateRawSync(text, { level: 9 });
  raw += text.length, packed += z.length;
  const lines: string[] = [];
  for (let k = 0; k < z.length; k += 24) lines.push("    " + [...z.subarray(k, k + 24)].map((b) => "0x" + b.toString(16).padStart(2, "0")).join(","));
  c += `static const uint8_t T${i}[] = {\n${lines.join(",\n")},\n};\n`;
  rows.push(`    {"${t.name}", "${t.title}", T${i}, sizeof T${i}, ${text.length}},`);
});
c += `\nconst man_topic_t MAN_TOPICS[] = {\n${rows.join("\n")}\n};\nconst size_t MAN_TOPICS_N = ${TOPICS.length};\n`;
writeFileSync(join(ROOT, "apps/man_data.c"), c);
console.log(`apps/man_data.c: ${TOPICS.length} topics, ${raw} bytes of text in ${packed}`);
