// The WAMR side of the API: system/src/api_wasm_glue.c (a stub per function and the NativeSymbol table for the import
// module) and system/src/api_impl.h (the prototypes the implementations in the system/api sources must match).
import { WASM_MODULE, type Func, type ModuleDef, ctype, declare, wasmSig } from "./model.ts";

const GENERATED = "GENERATED by forge/packages/apigen from the api/palanu headers. Do not edit: change the definitions and run\n * `bun forge/packages/apigen/src/cli.ts`.";

// The implementation's name: pal_write -> psys_api_write.
export function implName(f: Func): string {
  return `psys_api_${f.cname.slice("pal_".length)}`;
}

function activeFuncs(mods: ModuleDef[]): Func[] {
  return mods.flatMap((m) => m.funcs).filter((f) => f.removed === undefined);
}

// One stub: check the capability, call the implementation with the app's context, then let the runtime end the app if
// the implementation asked for it (exit, interrupt). Parameters are a0..an so they cannot clash with the locals.
function stub(f: Func): string[] {
  const params = f.params.map((p, i) => declare(`a${i}`, p.type, true));
  const args = ["ctx", ...f.params.map((_, i) => `a${i}`)].join(", ");
  const sig = ["wasm_exec_env_t env", ...params].join(", ");
  const isVoid = f.ret.k === "void";
  const out = [`static ${isVoid ? "void" : ctype(f.ret, true)} g_${f.cname}(${sig}) {`, "    api_ctx_t *ctx = api_ctx_of(env);"];
  if (f.cap) {
    out.push(`    if (!api_cap_ok(env, "${f.cap}")) return${isVoid ? "" : " NEMA_ERR_PERM"};`);
  }
  if (isVoid) out.push(`    ${implName(f)}(${args});`);
  else out.push(`    ${ctype(f.ret, true)} r = ${implName(f)}(${args});`);
  out.push("    api_after(env, ctx);");
  if (!isVoid) out.push("    return r;");
  out.push("}");
  return out;
}

export function emitGlue(mods: ModuleDef[]): string {
  const funcs = activeFuncs(mods);
  const out: string[] = [
    `/* ${GENERATED}`,
    " * The import module \"" + WASM_MODULE + "\" of WebAssembly apps. Each stub checks the capability its definition",
    " * names, calls the implementation in the system/api sources, and then ends the app if that asked it to stop. */",
    "#include <stdint.h>",
    "",
    "#include \"nema/nema.h\"",
    "#include \"api_impl.h\"",
    "#include \"api_wasm.h\"",
    "",
  ];
  for (const f of funcs) out.push(...stub(f), "");
  out.push(`NativeSymbol api_${WASM_MODULE}_natives[] = {`);
  for (const f of funcs) out.push(`    {"${f.wasm}", g_${f.cname}, "${wasmSig(f)}", NULL},`);
  out.push("};", `uint32_t api_${WASM_MODULE}_natives_count = sizeof(api_${WASM_MODULE}_natives) / sizeof(api_${WASM_MODULE}_natives[0]);`, "");
  return out.join("\n");
}

export function emitImplHeader(mods: ModuleDef[]): string {
  const out: string[] = [
    `/* ${GENERATED}`,
    " * The contract between the glue (api_wasm_glue.c) and the system/api implementations: each implementation",
    " * has exactly the prototype below. Removed functions have none. */",
    "#ifndef SYSTEM_API_IMPL_H",
    "#define SYSTEM_API_IMPL_H",
    "",
    "#include <stdint.h>",
    "",
    "#include \"api_ctx.h\"",
    "",
  ];
  for (const f of activeFuncs(mods)) {
    const params = ["api_ctx_t *c", ...f.params.map((p) => declare(p.name, p.type, true))].join(", ");
    out.push(`${ctype(f.ret, true)} ${implName(f)}(${params});`);
  }
  out.push("", "#endif", "");
  return out.join("\n");
}
